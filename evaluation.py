# ---------------------------------------------------------------------------
# Golden-set template
# ---------------------------------------------------------------------------

def create_golden_template(path: Path, rows: int = 200) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(f"Refusing to overwrite existing golden set: {path}")
    frame = pd.DataFrame({
        "id": range(1, rows + 1),
        "customer_message": [""] * rows,
        "intent": [""] * rows,
        "should_escalate": [""] * rows,
        "expected_resolution": [""] * rows,
        "difficulty": [""] * rows,
        "evidence_conversation_id": [""] * rows,
    })
    frame.to_csv(path, index=False)
    print(f"Created blank {rows}-row golden-set template at {path}")
    print("Use generate_golden.py for a stratified pre-filled template instead.")


# ---------------------------------------------------------------------------
# Classifier evaluation
# ---------------------------------------------------------------------------

def evaluate_classifier(model: Any, data: pd.DataFrame, label: str = "") -> dict[str, Any]:
    texts = data["customer_message"].astype(str).tolist()
    actual = data["intent"].astype(str).tolist()
    predicted = model.predict(texts)
    labels = sorted(set(actual) | set(predicted))
    result = {
        "label": label,
        "n": len(actual),
        "accuracy": round(accuracy_score(actual, predicted), 4),
        "macro_f1": round(f1_score(actual, predicted, average="macro", zero_division=0), 4),
        "weighted_f1": round(f1_score(actual, predicted, average="weighted", zero_division=0), 4),
        "precision_macro": round(precision_score(actual, predicted, average="macro", zero_division=0), 4),
        "recall_macro": round(recall_score(actual, predicted, average="macro", zero_division=0), 4),
        "classification_report": classification_report(actual, predicted, labels=labels, output_dict=True, zero_division=0),
        "confusion_matrix": confusion_matrix(actual, predicted, labels=labels).tolist(),
        "labels": labels,
    }
    if label == "golden_set":
        result["disclaimer"] = (
            "This is the PRIMARY evaluation result. Labels are independently hand-annotated "
            "and were never used for training."
        )
    elif label == "weak_label_test":
        result["disclaimer"] = (
            "SECONDARY result only. Test labels were generated by the same keyword rules used "
            "for training labels. This measures rule reproduction, not real intent accuracy. "
            "Do not report this as the headline accuracy."
        )
    return result


