"""Evaluation utilities for the AppleSupport AI system.

Evaluation hierarchy:
  1. PRIMARY: golden set (hand-labelled, independent of training labels)
  2. SECONDARY: weak-label test split (conversation-group-safe, but NOT ground-truth-safe)

The weak-label result is reported with an explicit disclaimer.
The golden-set result is the credible headline number.

LLM judge uses local Ollama (default: qwen2.5:7b). No API key required.
Ollama must be running: ollama serve && ollama pull qwen2.5:7b
"""

