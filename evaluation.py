def evaluate_retrieval(agent: SupportAgent, golden: pd.DataFrame, top_k: int = 5) -> dict[str, Any]:
    if "evidence_conversation_id" not in golden.columns:
        return {"status": "skipped", "reason": "Golden set has no evidence_conversation_id column"}
    expected = golden["evidence_conversation_id"].astype(str).str.strip()
    valid = golden[expected != ""]
    if valid.empty:
        return {"status": "skipped", "reason": "No evidence_conversation_id values populated in golden set"}
    hits = {f"recall_at_{k}": 0 for k in (1, 3, 5)}
    for _, row in valid.iterrows():
        results = agent.retriever.search(str(row["customer_message"]), top_k=top_k)
        retrieved_ids = [str(item.get("conversation_id", "")) for item in results]
        for k in (1, 3, 5):
            hits[f"recall_at_{k}"] += int(str(row["evidence_conversation_id"]) in retrieved_ids[:k])
    n = len(valid)
    return {"evaluated": n, **{key: round(value / n, 4) for key, value in hits.items()}}


# ---------------------------------------------------------------------------
# Escalation evaluation
# ---------------------------------------------------------------------------

def evaluate_escalation(agent: SupportAgent, golden: pd.DataFrame) -> dict[str, Any]:
    required = {"should_escalate", "customer_message"}
    if not required.issubset(golden.columns):
        return {"status": "skipped", "reason": f"Golden set needs {sorted(required)}"}
    subset = golden[golden["should_escalate"].astype(str).str.lower().isin(
        {"true", "false", "1", "0", "yes", "no"})].copy()
    if subset.empty:
        return {"status": "skipped", "reason": "No populated should_escalate labels"}
    actual = subset["should_escalate"].astype(str).str.lower().isin({"true", "1", "yes"}).astype(int)

    # Evaluate the escalation decision directly — no reply generation, no Ollama call.
    # Mirrors SupportAgent.respond() but skips the ReplyGenerator step entirely.
    predicted = []
    for msg in subset["customer_message"]:
        msg = str(msg)
        probs = agent.classifier.predict_proba([msg])[0]
        confidence = float(np.max(probs))
        evidence = agent.retriever.search(msg, top_k=5)
        escalate, _ = agent.policy.decide(confidence, evidence, msg)
        predicted.append(int(escalate))

    false_auto = sum(int(a == 1 and p == 0) for a, p in zip(actual, predicted))
    return {
        "evaluated": len(subset),
        "precision": round(precision_score(actual, predicted, zero_division=0), 4),
        "recall": round(recall_score(actual, predicted, zero_division=0), 4),
        "f1": round(f1_score(actual, predicted, zero_division=0), 4),
        "false_auto_count": false_auto,
        "false_auto_rate": round(false_auto / len(subset), 4),
        "note": "false_auto_rate is the critical safety metric: cases that should escalate but were auto-handled.",
    }


def evaluate_golden_coverage(golden: pd.DataFrame) -> dict[str, Any]:
    intent_counts = golden["intent"].astype(str).str.strip().value_counts().to_dict() if "intent" in golden else {}
    evidence_count = int(golden["evidence_conversation_id"].astype(str).str.strip().ne("").sum()) if "evidence_conversation_id" in golden else 0
    return {
        "rows": len(golden),
        "intent_counts": intent_counts,
        "insufficient_information_count": int(intent_counts.get("insufficient_information", 0)),
        "evidence_conversation_id_count": evidence_count,
        "warnings": [
            warning for warning in (
                "Golden set has no insufficient_information examples." if intent_counts.get("insufficient_information", 0) == 0 else "",
                "Retrieval Recall@K is not valid until evidence_conversation_id is populated." if evidence_count == 0 else "",
            ) if warning
        ],
    }


