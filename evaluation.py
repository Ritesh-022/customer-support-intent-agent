# LLM judge
# ---------------------------------------------------------------------------

def llm_judge_score(message: str, intent: str, evidence: list[dict], reply: str,
                    expected_resolution: str, model: str,
                    ollama_url: str = "http://localhost:11434/api/chat") -> dict[str, Any]:
    """Ask a local Ollama model to score a generated reply on four dimensions (1-5)."""
    import requests as _requests
    evidence_text = "\n\n".join(
        f"Historical customer: {e['customer']}\nHistorical response: {e['response']}"
        for e in evidence
    )
    prompt = (
        "You are evaluating an Apple Support AI reply. Score each dimension 1-5.\n\n"
        f"Customer message: {message}\n"
        f"Detected intent: {intent}\n"
        f"Expected resolution: {expected_resolution or 'not specified'}\n\n"
        f"Historical evidence used:\n{evidence_text or 'none'}\n\n"
        f"Generated reply:\n{reply}\n\n"
        "Return ONLY valid JSON with these exact keys and integer scores 1-5:\n"
        "{"
        "\"groundedness\": <1-5>, "
        "\"helpfulness\": <1-5>, "
        "\"safety\": <1-5>, "
        "\"overall\": <1-5>, "
        "\"reason\": \"<one sentence>\""
        "}"
    )
    response = _requests.post(
        ollama_url,
        json={
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "stream": False,
            "options": {"temperature": 0},
            "format": "json",
        },
        timeout=120,
    )
    response.raise_for_status()
    return json.loads(response.json()["message"]["content"])


def evaluate_llm_judge(agent: SupportAgent, golden: pd.DataFrame,
                       model: str = "qwen2.5:7b", max_rows: int = 50,
                       ollama_url: str = "http://localhost:11434/api/chat") -> dict[str, Any]:
    """Run local Ollama judge on up to max_rows golden examples that have intent labels."""
    import requests as _requests
    try:
        _requests.get("http://localhost:11434", timeout=3)
    except Exception:
        return {"status": "skipped", "reason": "Ollama not reachable at localhost:11434. Run: ollama serve"}
    labeled = golden[golden["intent"].astype(str).str.strip().ne("")].head(max_rows)
    if labeled.empty:
        return {"status": "skipped", "reason": "No labeled rows in golden set"}
    scores: list[dict[str, Any]] = []
    for _, row in labeled.iterrows():
        msg = str(row["customer_message"])
        result = agent.respond(msg)
        try:
            score = llm_judge_score(
                message=msg,
                intent=str(row["intent"]),
                evidence=result["historical_evidence"],
                reply=result["reply"],
                expected_resolution=str(row.get("expected_resolution", "")),
                model=model,
                ollama_url=ollama_url,
            )
            score["id"] = row.get("id", "")
            scores.append(score)
        except Exception as exc:
            scores.append({"id": row.get("id", ""), "error": str(exc)})
    valid = [s for s in scores if "groundedness" in s]
    if not valid:
        return {"status": "failed", "reason": "No valid scores returned", "raw": scores}
    avg = {dim: round(sum(s[dim] for s in valid) / len(valid), 3)
           for dim in ("groundedness", "helpfulness", "safety", "overall")}
    return {"evaluated": len(valid), "averages": avg, "per_row": scores,
            "note": "Scores are 1-5 from local Ollama judge. Use human_agreement to validate reliability."}


# ---------------------------------------------------------------------------
# Human-vs-LLM agreement
# ---------------------------------------------------------------------------

def evaluate_human_agreement(judge_scores_path: Path, human_scores_path: Path) -> dict[str, Any]:
    """Compare LLM judge scores against human scores. Both CSVs need id + dimension columns."""
    if not judge_scores_path.exists() or not human_scores_path.exists():
        return {"status": "skipped", "reason": "Provide --judge-scores and --human-scores CSV paths"}
    judge = pd.read_csv(judge_scores_path).fillna("")
    human = pd.read_csv(human_scores_path).fillna("")
    merged = judge.merge(human, on="id", suffixes=("_llm", "_human"))
    if merged.empty:
        return {"status": "skipped", "reason": "No matching IDs between judge and human scores"}
    dims = [d for d in ("groundedness", "helpfulness", "safety", "overall")
            if f"{d}_llm" in merged.columns and f"{d}_human" in merged.columns]
    result: dict[str, Any] = {"n": len(merged), "dimensions": {}}
    for dim in dims:
        # Drop rows where either the LLM or human score is blank/missing
        col_llm = f"{dim}_llm"
        col_human = f"{dim}_human"
        subset = merged[
            merged[col_llm].astype(str).str.strip().ne("") &
            merged[col_human].astype(str).str.strip().ne("")
        ].copy()
        if subset.empty:
            result["dimensions"][dim] = {
                "status": "skipped",
                "reason": f"No filled human scores for '{dim}'. Fill in {human_scores_path.name} and rerun.",
            }
            continue
        llm_vals = pd.to_numeric(subset[col_llm], errors="coerce").dropna().tolist()
        human_vals = pd.to_numeric(subset[col_human], errors="coerce").dropna().tolist()
        # Align lengths after numeric coercion
        n = min(len(llm_vals), len(human_vals))
        if n == 0:
            result["dimensions"][dim] = {"status": "skipped", "reason": "No numeric scores after parsing"}
            continue
        llm_vals, human_vals = llm_vals[:n], human_vals[:n]
        exact = sum(int(a == b) for a, b in zip(llm_vals, human_vals)) / n
        within1 = sum(int(abs(a - b) <= 1) for a, b in zip(llm_vals, human_vals)) / n
        try:
            kappa = round(float(cohen_kappa_score(
                [round(v) for v in llm_vals], [round(v) for v in human_vals])), 4)
        except Exception:
            kappa = None
        result["dimensions"][dim] = {
            "n_scored": n,
            "exact_agreement": round(exact, 4),
            "within_1_agreement": round(within1, 4),
            "cohen_kappa": kappa,
        }
    return result


