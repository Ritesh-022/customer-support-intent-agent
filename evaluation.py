_HYPOTHESES: dict[tuple[str, str], str] = {
    ("app_software_issue", "device_issue"): (
        "Device nouns (iPhone, iPad, Mac) appear in both intents. When a message mentions a device "
        "name without explicit software terms, the classifier over-weights the device noun and "
        "predicts device_issue even when the actual problem is software."
    ),
    ("device_issue", "app_software_issue"): (
        "Messages about physical hardware failures sometimes include software-adjacent words "
        "(e.g. 'update', 'restart') as attempted fixes, causing the classifier to predict "
        "app_software_issue instead of the underlying hardware intent."
    ),
    ("account_access", "app_software_issue"): (
        "iCloud sync and sign-in failures share vocabulary with software errors. "
        "The classifier may predict app_software_issue when the root cause is account access."
    ),
    ("connectivity_issue", "app_software_issue"): (
        "Network problems after iOS updates are described with both connectivity and software terms. "
        "The classifier attributes the intent to software rather than the network layer."
    ),
    ("subscription", "billing_payment"): (
        "Subscription renewal charges are described with billing vocabulary, causing the classifier "
        "to predict billing_payment instead of the more specific subscription intent."
    ),
    ("insufficient_information", "app_software_issue"): (
        "Very short messages that mention a device name get pulled toward app_software_issue "
        "because device names were historically strong signals in the weak-label rules."
    ),
}


def _hypothesis(gold: str, pred: str, examples: list[str]) -> str:
    if (gold, pred) in _HYPOTHESES:
        return _HYPOTHESES[(gold, pred)]
    return (
        f"Messages labeled '{gold}' are predicted as '{pred}'. "
        f"Inspect examples for shared lexical patterns that overlap with '{pred}' "
        f"patterns in the weak-supervision rules."
    )


def analyze_failure_modes(model: Any, data: pd.DataFrame, top_n: int = 5) -> list[dict[str, Any]]:
    """Find the top-N most common misclassification patterns with real hypotheses."""
    texts = data["customer_message"].astype(str).tolist()
    actual = data["intent"].astype(str).tolist()
    predicted = model.predict(texts)
    errors: dict[tuple[str, str], list[str]] = {}
    for text, gold, pred in zip(texts, actual, predicted):
        if gold != pred:
            errors.setdefault((gold, pred), []).append(text)
    ranked = sorted(errors.items(), key=lambda item: -len(item[1]))[:top_n]
    return [
        {
            "gold_intent": gold,
            "predicted_intent": pred,
            "count": len(examples),
            "examples": examples[:3],
            "hypothesis": _hypothesis(gold, pred, examples),
        }
        for (gold, pred), examples in ranked
    ]


